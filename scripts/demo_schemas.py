"""Demonstration Script for Pydantic Data Contracts and Schemas (Step 9).

Showcases end-to-end schema validation across the hybrid AI pipeline components:
1. Inbound AnalysisRequest validation and sanitization.
2. RedFlagResult validation using actual Step 8 detector output.
3. MLAssessment validation using the frozen classical model on a sample statement.
4. Mock contract-level LLMAssessment demonstration (strictly labeled as mock).
5. FinalAssessment schema example demonstrating verdict/abstention consistency.
6. Complete AnalysisResponse JSON serialization and round-trip verification.

IMPORTANT:
This script demonstrates data contracts ONLY.
Zero live LLM calls, zero model training, and zero database writes are performed.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

# Ensure repository root is on sys.path
REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from backend.app.schemas import (
    AnalysisRequest,
    AnalysisResponse,
    Claim,
    ClaimAssessment,
    ClaimResult,
    ComponentExecutionStatus,
    ComponentStatus,
    EvidenceItem,
    EvidenceStance,
    EvidenceSupport,
    FinalAssessment,
    InternalConsistency,
    LLMAssessment,
    MLAssessment,
    MLLabel,
    RedFlagResult,
    SourceAttribution,
    VerdictLabel,
    adapter_from_classical_prediction,
    adapter_from_red_flags,
)
from backend.app.services.baseline_model import (
    load_baseline_pipeline,
    predict_baseline,
)
from backend.app.services.dataset_loader import get_project_root
from backend.app.services.red_flags import analyze_red_flags


def run_schema_demo() -> None:
    """Execute structured data contract validation demonstration."""
    print("=" * 80)
    print("STRUCTURED DATA CONTRACTS DEMONSTRATION (STEP 9)")
    print("=" * 80)

    # 1. Inbound Request Validation
    sample_text = (
        "   BREAKING: According to the Department of Labor, unemployment fell to 3.8% this quarter.   "
    )
    print("\n[1] Inbound AnalysisRequest Validation:")
    request = AnalysisRequest(text=sample_text)
    print(f"    Raw input length : {len(sample_text)} characters")
    print(f"    Trimmed text     : \"{request.text}\"")
    print(f"    Validated length : {len(request.text)} characters")

    # 2. Step 8 Red-Flag Integration
    print("\n[2] Red-Flag Detector Schema Validation (Step 8 Integration):")
    raw_red_flags = analyze_red_flags(request.text)
    validated_red_flags = adapter_from_red_flags(raw_red_flags)
    print(f"    Extracted features : {validated_red_flags.features.word_count} words, "
          f"{validated_red_flags.features.percentage_count} percentage, "
          f"attribution={validated_red_flags.summary.has_attribution}")
    print(f"    Emitted flags count: {validated_red_flags.summary.total_flags}")
    for flag in validated_red_flags.flags:
        print(f"      - [{flag.severity.value.upper()}] {flag.type}: {flag.message} (snippet: \"{flag.snippet}\")")

    # 3. Classical ML Model Integration
    print("\n[3] Classical ML Baseline Schema Validation (Step 6.5 / 7 Integration):")
    model_path = get_project_root() / "models" / "classical_best_validation.joblib"
    pipeline = load_baseline_pipeline(model_path)
    raw_prediction = predict_baseline(pipeline, request.text)
    validated_ml = adapter_from_classical_prediction(
        raw_prediction, model_name="Frozen Word TF-IDF + Logistic Regression"
    )
    print(f"    Model Name         : {validated_ml.model_name}")
    print(f"    Predicted Label    : {validated_ml.label.value} (MLLabel domain)")
    print(f"    Class Probabilities: fake={validated_ml.probabilities.likely_fake:.4f}, "
          f"reliable={validated_ml.probabilities.likely_reliable:.4f}, "
          f"misleading={validated_ml.probabilities.misleading:.4f}")

    # 4. Mock Contract-Level LLMAssessment (Schema Example Only)
    print("\n[4] Mock LLMAssessment Schema Validation:")
    print("    [NOTICE: Schema example only — not generated by a live LLM]")
    mock_llm = LLMAssessment(
        label=VerdictLabel.likely_reliable,
        source_attribution=SourceAttribution.strong,
        evidence_support=EvidenceSupport.supported,
        internal_consistency=InternalConsistency.consistent,
        rhetorical_cues=["official institutional attribution", "specific quantitative rate"],
        unsupported_claims=[],
        short_reason="Statement cites verified Department of Labor quarterly employment metrics.",
    )
    print(f"    Evaluated Verdict  : {mock_llm.label.value}")
    print(f"    Attribution Quality: {mock_llm.source_attribution.value}")
    print(f"    Evidence Support   : {mock_llm.evidence_support.value}")
    print(f"    Short Justification: \"{mock_llm.short_reason}\"")

    # 5. Final Assessment Schema Example
    print("\n[5] FinalAssessment Schema Example (Enforcing Abstention Consistency):")
    final_assessment = FinalAssessment(
        verdict=VerdictLabel.likely_reliable,
        support_score=0.82,
        reason="Corroborated by classical text baseline and official Department of Labor statistics.",
        abstained=False,
        signals_used=["classical_ml", "red_flags", "structured_llm"],
    )
    print(f"    Final Verdict : {final_assessment.verdict.value}")
    print(f"    Support Score : {final_assessment.support_score:.2f} (Internal decision-support score)")
    print(f"    Abstained     : {final_assessment.abstained}")
    print(f"    Signals Used  : {final_assessment.signals_used}")

    # 6. End-to-End AnalysisResponse Assembly & Serialization
    print("\n[6] Assembling and Serializing Complete AnalysisResponse:")
    response = AnalysisResponse(
        analysis_id="demo_req_001",
        input_text=request.text,
        verdict=final_assessment.verdict,
        support_score=final_assessment.support_score,
        claims=[
            ClaimResult(
                claim=Claim(
                    id=1,
                    text="Unemployment fell to 3.8% this quarter.",
                    checkable=True,
                    source_span="unemployment fell to 3.8% this quarter",
                ),
                assessment=ClaimAssessment.supported,
                evidence=[
                    EvidenceItem(
                        id="ev_01",
                        claim_summary="Q3 unemployment rate reached 3.8%",
                        evidence_text="Bureau of Labor Statistics reported non-farm unemployment at 3.8%.",
                        source_name="U.S. Bureau of Labor Statistics",
                        similarity_score=0.91,
                        stance=EvidenceStance.supports,
                    )
                ],
                explanation="Official statistical bulletin confirms 3.8% rate.",
            )
        ],
        red_flags=validated_red_flags,
        ml=validated_ml,
        llm=mock_llm,
        evidence=[],
        reason=final_assessment.reason,
        component_statuses=[
            ComponentStatus(component="classical_ml", status=ComponentExecutionStatus.success),
            ComponentStatus(component="red_flags", status=ComponentExecutionStatus.success),
            ComponentStatus(
                component="llm",
                status=ComponentExecutionStatus.success,
                message="Mock contract demonstration.",
            ),
        ],
        created_at=datetime.now(timezone.utc),
    )

    json_payload = response.model_dump_json(indent=2)
    print("    Serialization successful!")
    print(f"    Payload size: {len(json_payload):,} bytes")
    print(f"    Verified round-trip: {AnalysisResponse.model_validate_json(json_payload).verdict.value}")

    print("\n" + "=" * 80)
    print("SCHEMA DEMONSTRATION COMPLETE (ALL CONTRACTS VALIDATED)")
    print("=" * 80)


if __name__ == "__main__":
    run_schema_demo()
